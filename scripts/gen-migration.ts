/**
 * Generates migrations/20261123090000_seed-tables.sql from the zod seed schemas, so the
 * Postgres tables can never drift from lib/domain/schemas. Run: pnpm db:gen
 */
import fs from "node:fs";
import path from "node:path";
import { z } from "zod";
import { SeedFiles } from "../lib/domain/schemas";

type Def = { type: string; innerType?: z.ZodType; checks?: { _zod: { def: { check?: string; format?: string } } }[] };
const def = (t: z.ZodType) => (t as unknown as { _zod: { def: Def } })._zod.def;

function sqlType(t: z.ZodType): { type: string; nullable: boolean } {
  let d = def(t);
  let nullable = false;
  while (d.type === "nullable" || d.type === "optional" || d.type === "default") {
    if (d.type !== "default") nullable = true;
    t = d.innerType!;
    d = def(t);
  }
  switch (d.type) {
    case "string":
    case "enum":
    case "literal":
      return { type: "text", nullable };
    case "number":
      return { type: (d.checks ?? []).some((c) => c._zod.def.format === "safeint" || c._zod.def.check === "number_format") ? "integer" : "numeric", nullable };
    case "boolean":
      return { type: "boolean", nullable };
    default:
      return { type: "jsonb", nullable };
  }
}

const out: string[] = [
  "-- Generated by scripts/gen-migration.ts from lib/domain/schemas. Do not edit by hand.",
  "-- Seed tables: immutable rows loaded by `pnpm db:seed` (session_id is always null for seed rows).",
  "",
];
for (const [name, arr] of Object.entries(SeedFiles)) {
  const obj = def(arr as z.ZodType) as unknown as { element: z.ZodObject };
  const shape = obj.element.shape as Record<string, z.ZodType>;
  const cols = Object.entries(shape).map(([col, t]) => {
    const { type, nullable } = sqlType(t);
    const pk = col === "id" ? " primary key" : "";
    return `  "${col}" ${type}${pk}${!nullable && col !== "id" ? " not null" : ""}`;
  });
  if (!("firm_id" in shape)) cols.push(`  "firm_id" text not null default 'rypples'`);
  cols.push(`  "created_at" timestamptz not null default now()`);
  out.push(`create table if not exists public."${name}" (\n${cols.join(",\n")}\n);`);
  out.push(`alter table public."${name}" enable row level security;`);
  out.push("");
}
const file = path.join(process.cwd(), "migrations/20261123090000_seed-tables.sql");
fs.writeFileSync(file, out.join("\n"));
console.log(`wrote ${file}`);
